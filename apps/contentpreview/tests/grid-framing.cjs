const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const mod = { exports: {} };
const source = fs.readFileSync(path.resolve(__dirname, '../lib/grid-framing.ts'), 'utf8');
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { module: mod, exports: mod.exports });
const { coverSize, dragCropPosition } = mod.exports;
const landscape = coverSize(200, 250, 1600, 900);
assert.equal(landscape.height, 250);
assert.ok(landscape.width > 440);
assert.equal(dragCropPosition(50, 20, 200, 200, 100), 50, 'Uncropped axis stays centered');
assert.equal(dragCropPosition(50, 20, 200, 200, 150), 30, 'Zoomed same-aspect photo follows the cursor');
assert.equal(dragCropPosition(50, -20, 200, 200, 150), 70);
assert.equal(dragCropPosition(50, 900, 200, 400, 100), 0, 'Clamp left edge');
assert.equal(dragCropPosition(50, -900, 200, 400, 100), 100, 'Clamp right edge');
assert.equal(dragCropPosition(50, 30, 200, 400, 100), 35, 'Cover overflow scales gesture correctly');
console.log('PASS: cover geometry, same-aspect zoom, drag direction and crop bounds.');
