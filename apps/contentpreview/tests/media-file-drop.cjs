const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const { File } = require('node:buffer');
const source = fs.readFileSync(path.resolve(__dirname, '../lib/media-file-drop.ts'), 'utf8');
const moduleUnderTest = { exports: {} };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { module: moduleUnderTest, exports: moduleUnderTest.exports, File });
const { isFileTransfer, prepareDroppedMedia, bindMediaFileDrop } = moduleUnderTest.exports;
const transfer = files => ({ types: ['Files'], items: files.map(() => ({ kind: 'file' })), files, dropEffect: 'none' });
const jpeg = new File(['photo'], 'dinner.jpg', { type: 'image/jpeg' });
const video = new File(['video'], 'evening.mp4', { type: 'video/mp4' });
const emptyMime = new File(['photo'], 'DINNER.JPG');
const invalid = new File(['document'], 'notes.txt', { type: 'text/plain' });
const drag = transfer([jpeg, video, emptyMime, invalid]);
assert.equal(isFileTransfer(null), false);
assert.equal(isFileTransfer(transfer([])), true, 'Files is detectable during protected dragover before files are readable');
const internal = { types: ['text/plain'], items: [{ kind: 'string' }], files: [] };
assert.equal(isFileTransfer(internal), false, 'Internal post/media drags must not be intercepted');
const prepared = prepareDroppedMedia(drag);
assert.equal(prepared.files.length, 3);
assert.equal(prepared.files[0], jpeg); assert.equal(prepared.files[1], video);
assert.equal(prepared.files[2].type, 'image/jpeg');
assert.equal(prepared.files[2].name, 'DINNER.JPG');
assert.equal(prepared.rejected[0], 'notes.txt');
assert.equal(prepareDroppedMedia(transfer([])).files.length, 0, 'Empty/folder-only drops do not queue uploads');
class Surface extends EventTarget {
  send(type, dataTransfer) {
    const event = new Event(type, { cancelable: true });
    event.dataTransfer = dataTransfer;
    this.dispatchEvent(event);
    return event;
  }
}
const root = new Surface(), page = new Surface();
const hover = [], uploads = [];
const cleanup = bindMediaFileDrop(root, active => hover.push(active), data => uploads.push(prepareDroppedMedia(data).files), page);
assert.equal(root.send('dragover', internal).defaultPrevented, false);
assert.equal(root.send('drop', internal).defaultPrevented, false);
assert.equal(uploads.length, 0);
root.send('dragenter', transfer([])); root.send('dragenter', transfer([]));
root.send('dragleave', transfer([]));
assert.deepEqual(hover, [true], 'Moving between nested thumbnails must not flicker the target');
assert.equal(root.send('dragover', drag).defaultPrevented, true);
assert.equal(drag.dropEffect, 'copy');
assert.equal(root.send('drop', drag).defaultPrevented, true);
assert.equal(uploads.length, 1, 'One drop queues one multi-file batch');
assert.equal(uploads[0].length, 3); assert.deepEqual(hover, [true, false]);
root.send('dragenter', drag); root.send('dragleave', drag);
assert.deepEqual(hover.slice(-2), [true, false], 'Leaving the target resets highlighting');
root.send('dragenter', drag); page.send('dragend', drag);
assert.equal(hover.at(-1), false);
root.send('dragenter', drag); page.send('blur', drag);
assert.equal(hover.at(-1), false, 'Cancelling or leaving the window clears the overlay');
assert.equal(page.send('dragover', drag).defaultPrevented, true);
assert.equal(drag.dropEffect, 'none');
assert.equal(page.send('drop', drag).defaultPrevented, true, 'Missed drops cannot navigate away');
assert.equal(uploads.length, 1, 'Drops outside the library never upload or replace a post');
assert.equal(page.send('drop', internal).defaultPrevented, false);
cleanup();
assert.equal(root.send('drop', drag).defaultPrevented, false);
assert.equal(page.send('drop', drag).defaultPrevented, false, 'Unmount removes global listeners');
assert.equal(uploads.length, 1);
const workspace = fs.readFileSync(path.resolve(__dirname, '../components/ysabel-workspace.tsx'), 'utf8');
assert.match(workspace, /MediaFileDrop as="aside" onFiles=\{uploadDroppedFiles\}/);
assert.match(workspace, /MediaFileDrop className="library-page" onFiles=\{uploadDroppedFiles\}/);
assert.match(workspace, /const uploadDroppedFiles = \(files: File\[\]\) => \{[\s\S]*?replaceTarget.current = null;[\s\S]*?void uploadFiles\(files\)/);
console.log('PASS: PC multi-file drop, protected dragover, mixed formats, missing MIME, nested targets, internal drags, cancellation, missed drops, cleanup and both library upload entry points.');
