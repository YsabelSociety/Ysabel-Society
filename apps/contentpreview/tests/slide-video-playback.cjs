const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const moduleUnderTest = { exports: {} };
const source = fs.readFileSync(path.resolve(__dirname, '../lib/slide-video-playback.ts'), 'utf8');
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { module: moduleUnderTest, exports: moduleUnderTest.exports });
const { bindSlideVideoPlayback, currentGridVideo, playVideoWithSound, pauseOtherPreviewVideos } = moduleUnderTest.exports;
const page = { hidden: false, listeners: new Set(), addEventListener(_, fn) { this.listeners.add(fn); }, removeEventListener(_, fn) { this.listeners.delete(fn); }, change(hidden) { this.hidden = hidden; this.listeners.forEach(fn => fn()); } };
const makeVideo = () => ({ paused: true, muted: true, volume: 0, playsInline: false, plays: 0, pauses: 0, play() { this.plays++; this.paused = false; return Promise.resolve(); }, pause() { this.pauses++; this.paused = true; } });
async function main() {
  const initial = makeVideo();
  const disposeInitial = bindSlideVideoPlayback(initial, 'manual', page);
  assert.equal(initial.plays, 0, 'Initial grid/library preview must not autoplay');
  disposeInitial();
  const first = makeVideo();
  const stopFirst = bindSlideVideoPlayback(first, 'active', page);
  assert.equal(first.plays, 1); assert.equal(first.muted, false); assert.equal(first.volume, 1); assert.equal(first.playsInline, true);
  stopFirst(); assert.equal(first.paused, true, 'Leaving a slide pauses it');
  const neighbour = bindSlideVideoPlayback(first, 'inactive', page);
  assert.equal(first.plays, 1, 'Adjacent mounted slides stay paused');
  const second = makeVideo();
  const stopSecond = bindSlideVideoPlayback(second, 'active', page);
  assert.equal(second.plays, 1, 'Next video starts automatically');
  page.change(true); assert.equal(second.paused, true);
  page.change(false); assert.equal(second.plays, 2);
  second.pause(); page.change(true); page.change(false);
  assert.equal(second.plays, 2, 'Manually paused video does not restart after switching tabs');
  stopSecond(); neighbour(); assert.equal(page.listeners.size, 0, 'No retained listeners after closing');
  let blockedPrompts = 0;
  const blocked = makeVideo(); blocked.play = () => Promise.reject(Object.assign(new Error('User gesture required'), { name: 'NotAllowedError' }));
  const stopBlocked = bindSlideVideoPlayback(blocked, 'active', page, () => blockedPrompts++);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(blockedPrompts, 1, 'Offer audible manual playback if autoplay is blocked');
  assert.equal(blocked.muted, false, 'Never silently fall back to muted playback');
  stopBlocked();
  const abandoned = bindSlideVideoPlayback(blocked, 'active', page, () => blockedPrompts++);
  abandoned(); await new Promise(resolve => setImmediate(resolve));
  assert.equal(blockedPrompts, 1, 'Ignore a late rejection after leaving the slide');
  const manual = makeVideo(); await playVideoWithSound(manual);
  assert.equal(manual.muted, false); assert.equal(manual.volume, 1); assert.equal(manual.plays, 1);
  const previous = makeVideo(); previous.paused = false;
  manual.ownerDocument = { querySelectorAll(selector) { assert.equal(selector, 'video[data-grid-video]'); return [previous, manual]; } };
  pauseOtherPreviewVideos(manual);
  assert.equal(previous.paused, true, 'Prevent overlapping audio from another grid post');
  assert.equal(manual.paused, false);
  page.hidden = true;
  const background = makeVideo(); const stopBackground = bindSlideVideoPlayback(background, 'active', page);
  assert.equal(background.plays, 0); page.change(false); assert.equal(background.plays, 1); stopBackground();
  assert.equal(currentGridVideo(null), null);
  const selection = currentGridVideo({ querySelector(selector) { assert.match(selector, /:not\(\[data-slide-playback="inactive"\]\)/); return second; } });
  assert.equal(selection, second, 'Grid play/pause targets only the active slide');
  console.log('PASS: audible slide playback, manual sound, no overlapping audio, hidden tabs, autoplay tap fallback, stale promises and cleanup.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
