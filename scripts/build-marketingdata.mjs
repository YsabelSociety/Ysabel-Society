import { spawnSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const directory = fileURLToPath(new URL('../apps/marketingdata/', import.meta.url));
const npm = process.env.npm_execpath;
if (!npm) throw new Error('Run this build through npm run build.');
const isPnpm = path.basename(npm).toLowerCase().includes('pnpm');
const installArgs = isPnpm ? ['install', '--no-frozen-lockfile', '--ignore-scripts']
  : ['ci', '--include=dev', '--ignore-scripts', '--no-audit', '--no-fund'];
for (const args of [installArgs, ['run', 'typecheck'], ['run', 'build']]) {
  const result = spawnSync(process.execPath, [npm, ...args], { cwd: directory, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
const paths = JSON.parse(readFileSync(path.join(directory, 'components/ysabel/emblem-paths.json'), 'utf8'));
const emblem = `<svg viewBox="548 128 824 824" fill="#1d3428" aria-hidden="true">${paths.map(d => `<path d="${d}"/>`).join('')}</svg>`;
const htmlPath = fileURLToPath(new URL('../public/marketingdata-ui/index.html', import.meta.url));
const html = readFileSync(htmlPath, 'utf8').replace('__YSABEL_BOOT_EMBLEM__', emblem);
writeFileSync(htmlPath, html);
const generated = fileURLToPath(new URL('../src/generated/', import.meta.url));
mkdirSync(generated, { recursive: true });
writeFileSync(path.join(generated, 'marketingdata-shell.ts'), `// Generated by build-marketingdata.mjs. Contains no reports or credentials.\nexport const marketingDataHtml = ${JSON.stringify(html)};\n`);
